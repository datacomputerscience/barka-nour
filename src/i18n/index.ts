export function t(key: string, lang: Language = 'fr'): string {
  return translations[lang]?.[key] || translations['fr'][key] || key
}

export function useTranslation(lang: Language) {
  return {
    t: (key: string) => t(key, lang),
    lang,
    dir: languages[lang].dir,
  }
}
